'use client';
import type { PropsWithChildren, ReactNode } from 'react';
import type { UIMatch } from 'react-router';
import { useMatches, useOutlet, useOutletContext } from 'react-router';

export function useUIMatches<Data, Handle>(): UIMatch<Data, Handle>[] {
  const matches = useMatches() as UIMatch<Data, Handle>[];
  const ret = new Map<string, UIMatch<Data, Handle>>();

  for (let match of matches) {
    const m = ret.get(match.pathname);
    if (m) {
      match = { ...m, ...match };
    }
    ret.set(match.pathname, match);
  }
  return Array.from(ret.values());
}

/**
 * render either the children or router outlet for the child routes on demand.
 * intent to be used with route entries generated by
 * `fileSystemRoutes({indexOutlet: true})`
 *
 * @example
 * #### app/routes.ts
 * ```tsx
 * export default fileSystemRoutes({indexOutlet: true});
 * ```
 * #### app/routes/dashboard/route.tsx
 * ```tsx
 * export default function DashboardRoute() {
 *   return <WithRouterOutlet>...</WithRouterOutlet>;
 * }
 * // now the route handle can be passed to any routes in decendant directory
 * // such as app/routes/dashboard/settings/route.tsx
 * export const handle = {category: null, title: 'home', ...};
 * ```
 */
export function WithRouterOutlet({ children }: PropsWithChildren): ReactNode {
  return useOutlet(useOutletContext()) ?? children;
}
